import test from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFileSync} from 'node:fs';
import {makeWorker} from '../worker/main.js';
const sql=readFileSync(new URL('../drizzle/0000_initial.sql',import.meta.url),'utf8');
test('two anonymous guests share persisted votes and manage tokens stay private',async()=>{
 const sqlite=new DatabaseSync(':memory:'); sqlite.exec(sql); sqlite.exec(readFileSync(new URL('../drizzle/0001_public_pool.sql',import.meta.url),'utf8'));
 const wrap=(query,params=[])=>({bind:(...a)=>wrap(query,a),first:async()=>sqlite.prepare(query).get(...params)??null,all:async()=>({results:sqlite.prepare(query).all(...params)}),run:async()=>sqlite.prepare(query).run(...params)});
 const DB={prepare:wrap,batch:async list=>{sqlite.exec('BEGIN');try{const r=await Promise.all(list.map(s=>s.run()));sqlite.exec('COMMIT');return r;}catch(e){sqlite.exec('ROLLBACK');throw e;}}};
 const worker=makeWorker({'/index.html':['text/html','test']});
 const guest=()=>({cookie:''});
 const a=guest(),b=guest(),c=guest();
 const call=async(who,path,method='GET',data,token,origin)=>{
  const headers=new Headers(who.cookie?{cookie:who.cookie}:{});
  if(data!==undefined)headers.set('content-type','application/json');
  if(token)headers.set('Authorization','Bearer '+token);
  if(origin)headers.set('Origin',origin);
  const res=await worker.fetch(new Request('https://test.test'+path,{method,headers,body:data===undefined?undefined:JSON.stringify(data)}),{DB});
  const cookie=res.headers.get('set-cookie');
  if(cookie)who.cookie=cookie.split(';')[0];
  return {status:res.status,data:res.headers.get('content-type').startsWith('application/json')?await res.json():await res.text()};
 };
 const seeded=await call(a,'/api/next');assert.equal(seeded.status,200);assert.equal(seeded.data.card.id,'demo-1');assert.equal('source' in seeded.data.card,false);
 assert.equal((await call(a,'/api/next?skip=demo-1')).data.card.id,'demo-2');
 assert.equal((await call(a,'/api/cards/demo-1/vote','POST',{choice:'human'})).data.result.provenance,'demo-ai');
 assert.equal((await call(a,'/api/next')).data.card.id,'demo-2');
 const creation=await call(a,'/api/cards','POST',{promptId:'cake',answer:'测试，不公开发布。',source:'human'});
 assert.equal(creation.status,201);
 const {id,manageToken}=creation.data, p='/api/cards/'+id, m='/api/manage/'+id;
 assert.equal((await call(b,p)).data.result,undefined);
 assert.equal((await call(b,'/api/next')).data.card.id,id);
 assert.notEqual((await call(a,'/api/next')).data.card.id,id);
 assert.equal((await call(b,'/api/next?lang=en')).data.card.id,'demo-en-1');
 assert.match((await call(b,'/api/prompts?lang=en')).data.prompts[0].text,/cake/);
 assert.match((await call(b,p+'?lang=en')).data.card.question,/cake/);
 assert.equal((await call(b,p+'?lang=en')).data.card.answer,'测试，不公开发布。');
 const eng=await call(c,'/api/cards?lang=en','POST',{promptId:'gift',answer:'It’s a long story.',source:'human',language:'en'});
 assert.equal(eng.status,201);
 assert.equal((await call(b,'/api/next?lang=en')).data.card.id,eng.data.id);
 assert.match((await call(b,'/api/manage/'+eng.data.id+'?lang=en')).data.error,/original browser/);
 assert.equal((await call(b,'/api/cards/'+eng.data.id+'/report','POST',{reason:'privacy'})).status,200);
 assert.equal((await call(a,'/api/cards/'+eng.data.id+'/report','POST',{reason:'privacy'})).status,200);
 assert.equal((await call(b,'/api/next?lang=en')).data.card.id,'demo-en-1');
 assert.equal((await call(a,p+'/vote','POST',{choice:'ai'})).status,403);
 assert.equal((await call(b,p+'/vote','POST',{choice:'ai'},null,'https://elsewhere.test')).status,403);
 const vote=await call(b,p+'/vote','POST',{choice:'ai'});
 assert.deepEqual(vote.data.result,{human:0,ai:1,source:'human',choice:'ai',provenance:'self-reported'});
 assert.equal((await call(b,p+'/vote','POST',{choice:'human'})).data.result.choice,'ai');
 assert.equal((await call(c,p+'/vote','POST',{choice:'human'})).data.result.human,1);
 assert.equal((await call(a,'/api/mine')).data.cards[0].ai,1);
 assert.equal((await call(b,m)).status,403);
 assert.equal((await call(b,m,'GET',undefined,manageToken)).data.card.human,1);
 assert.equal((await call(b,p+'/report','POST',{reason:'测试'})).status,200);
 assert.equal((await call(b,m,'DELETE',undefined,manageToken)).status,200);
 assert.equal((await call(c,p)).status,404);
 assert.equal((await call(a,'/api/mine')).data.cards.length,0);
 assert.equal(sqlite.prepare('SELECT answer FROM cards WHERE id=?').get(id).answer,'');
 assert.equal((await call(b,'/c/'+id)).data,'test');
});
